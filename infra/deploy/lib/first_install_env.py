#!/usr/bin/env python3
"""The environment files of a first install: generated, checked, and edited in place -- never printed.

`infra/deploy/first-install.sh` calls this; nothing else does. Standard library only, because a fresh server has
`python3` and nothing else of ours (`DEPLOYMENT_RUNBOOK.md` section 1 lists no virtual environment).

    first_install_env.py create --env-dir DIR --instance NAME --http-port N [--set NAME=VALUE]...
    first_install_env.py check  --env FILE [--provider FILE] --example FILE
    first_install_env.py get    --env FILE NAME
    first_install_env.py set    --env FILE NAME=VALUE...

WHAT `create` WRITES, AND WHY EVERY SECRET IS WRITTEN WHERE THE RUNBOOK SAYS (`DEPLOYMENT_RUNBOOK.md` section 2):

* `alpha.env` from `alpha.env.example` and `provider.env` from `provider.env.example`, both mode 600, both created with a hard
  link from a temporary file so that a file that already exists is **never overwritten, truncated or reordered**;
* the four secrets `deploy.sh`'s `placeholder-secrets` guard checks, each **again in the second place it is written**
  (`MIGRATOR_DATABASE_URL`, `S3_ACCESS_KEY_ID`, `S3_SECRET_ACCESS_KEY`: the `derived-secrets-coherent` guard, `D-103`), and the
  application role's password in `ALPHA_APP_DB_PASSWORD` **and** inside `DATABASE_URL` (`apply-grants.sh --config-only`);
* the X25519 pair of the executor key ring: the public half as `kid:base64` in `alpha.env`, the private half in `provider.env`
  (`AUDITMANAGER_SECRETS_KEYS`, read by the worker alone);
* `AUDITMANAGER_PROVIDER_MODE=live` and `AUDITMANAGER_PROVIDER_SOURCE=database`: the connections an administrator manages in
  «Исполнители», which is also what the card «Этот сервер» of `local-agent.sh` needs to receive runs.

**No secret is printed, logged or returned**: every message of this module names a variable, never a value.

Exit codes: 0 done; 2 usage; 3 a problem (the lines on stdout name it); 4 `create` found `alpha.env` already there and
changed nothing.
"""

from __future__ import annotations

import argparse
import base64
import os
import re
import secrets
import stat
import sys
import tempfile
import time
from collections.abc import Mapping, Sequence
from pathlib import Path

#: Instance names: the compose project, the three volumes and the S3 bucket derive from it, so lower-case letters, digits and
#: single hyphens inside; 3 to 40 characters; never a trailing hyphen (an S3 bucket name cannot end with one).
INSTANCE_PATTERN = re.compile(r"^[a-z][a-z0-9-]{1,38}[a-z0-9]$")
#: `apply-grants.sh`'s `app-role-well-formed`: the role is written into SQL and into a URL.
ROLE_PATTERN = re.compile(r"^[a-z_][a-z0-9_]{2,62}$")
#: `apply-grants.sh`'s `app-password-shape`.
APP_PASSWORD_PATTERN = re.compile(r"^[A-Za-z0-9._~-]{20,128}$")
KID_PATTERN = re.compile(r"^[A-Za-z0-9._-]{1,64}$")
#: The URL shape `deploy.sh` and `apply-grants.sh` both parse.
URL_PATTERN = re.compile(r"^postgresql\+psycopg://([^:@/]+):([^@/]+)@([^:@/]+):([0-9]+)/([^?]+)$")
NAME_PATTERN = re.compile(r"^[A-Z][A-Z0-9_]*$")
#: What a `--set` value may hold: no whitespace, quote, `$` or `#`, so the file stays what `sed` reads it as.
SET_VALUE_PATTERN = re.compile(r"^[A-Za-z0-9._:/@,=+-]*$")

#: Generated by `create`: a `--set` may not override them (it would weaken what this module guarantees).
GENERATED_NAMES = frozenset({
    "ALPHA_INSTANCE", "ALPHA_HTTP_PORT", "POSTGRES_DB", "POSTGRES_USER", "POSTGRES_PASSWORD", "ALPHA_APP_DB_USER",
    "ALPHA_APP_DB_PASSWORD", "MINIO_ROOT_USER", "MINIO_ROOT_PASSWORD", "S3_BUCKET", "DATABASE_URL",
    "MIGRATOR_DATABASE_URL", "S3_ACCESS_KEY_ID", "S3_SECRET_ACCESS_KEY", "AUDITMANAGER_API_TOKEN",
    "AUDITMANAGER_SECRETS_PUBLIC_KEYS", "AUDITMANAGER_SECRETS_ACTIVE_KID", "AUDITMANAGER_SECRETS_KEYS",
})
#: The four values `deploy.sh`'s `placeholder-secrets` guard refuses by identity with the example's own.
PLACEHOLDER_NAMES = ("POSTGRES_PASSWORD", "MINIO_ROOT_PASSWORD", "MINIO_ROOT_USER", "AUDITMANAGER_API_TOKEN")
#: Every name `check` demands set and non-empty in `alpha.env`.
REQUIRED_NAMES = (
    "ALPHA_INSTANCE", "ALPHA_HTTP_PORT", "POSTGRES_DB", "POSTGRES_USER", "POSTGRES_PASSWORD", "ALPHA_APP_DB_USER",
    "ALPHA_APP_DB_PASSWORD", "MINIO_ROOT_USER", "MINIO_ROOT_PASSWORD", "S3_BUCKET", "DATABASE_URL",
    "MIGRATOR_DATABASE_URL", "S3_ENDPOINT_URL", "S3_REGION", "S3_ACCESS_KEY_ID", "S3_SECRET_ACCESS_KEY",
    "AUDITMANAGER_API_TOKEN", "AUDITMANAGER_PROVIDER_MODE",
)
#: The only names `get` prints: nothing here is a secret or embeds one.
READABLE_NAMES = frozenset({
    "ALPHA_INSTANCE", "ALPHA_HTTP_PORT", "ALPHA_CERT_NAME", "ALPHA_ACME_EMAIL", "ALPHA_ACME_STAGING", "ALPHA_PUBLISH_HTTPS",
    "ALPHA_LOCAL_AGENT", "ALPHA_LOCAL_AGENT_USER", "ALPHA_BIND_ADDRESS", "ALPHA_TRUSTED_PROXY_CIDRS", "POSTGRES_DB",
    "S3_BUCKET", "AUDITMANAGER_PROVIDER_MODE", "AUDITMANAGER_PROVIDER_SOURCE",
})

# --------------------------------------------------------------------------------------------------------- X25519
# RFC 7748 section 5, in the standard library: the host has `python3` and not necessarily the `cryptography` package the
# application image carries. The tests pin it to the RFC's own vectors and, where the package exists, to the package.

_P = 2**255 - 19
_A24 = 121665


def x25519(scalar: bytes, u_coordinate: bytes) -> bytes:
    """RFC 7748 `X25519(k, u)`; both arguments 32 bytes, the scalar clamped here as the RFC says."""
    if len(scalar) != 32 or len(u_coordinate) != 32:
        raise ValueError("X25519 takes two 32-byte values")
    k = bytearray(scalar)
    k[0] &= 248
    k[31] &= 127
    k[31] |= 64
    k_int = int.from_bytes(k, "little")
    x1 = int.from_bytes(u_coordinate, "little") & ((1 << 255) - 1)
    x2, z2, x3, z3, swap = 1, 0, x1, 1, 0
    for t in range(254, -1, -1):
        k_t = (k_int >> t) & 1
        swap ^= k_t
        if swap:
            x2, x3 = x3, x2
            z2, z3 = z3, z2
        swap = k_t
        a = (x2 + z2) % _P
        aa = a * a % _P
        b = (x2 - z2) % _P
        bb = b * b % _P
        e = (aa - bb) % _P
        c = (x3 + z3) % _P
        d = (x3 - z3) % _P
        da = d * a % _P
        cb = c * b % _P
        x3 = pow(da + cb, 2, _P)
        z3 = x1 * pow(da - cb, 2, _P) % _P
        x2 = aa * bb % _P
        z2 = e * (aa + _A24 * e) % _P
    if swap:
        x2, x3 = x3, x2
        z2, z3 = z3, z2
    return (x2 * pow(z2, _P - 2, _P) % _P).to_bytes(32, "little")


def x25519_public(private: bytes) -> bytes:
    """The public key of a 32-byte private key: the scalar times the base point `u = 9`."""
    return x25519(private, (9).to_bytes(32, "little"))


def new_key_pair() -> tuple[bytes, bytes]:
    private = secrets.token_bytes(32)
    return private, x25519_public(private)


# ---------------------------------------------------------------------------------------------------- the file text


def _line_assigns(line: str, name: str) -> bool:
    """The reader `deploy.sh` uses: optional leading blanks, optional `export `, then `NAME=`."""
    return re.match(rf"^[ \t]*(export[ \t]+)?{re.escape(name)}=", line) is not None


def _line_templates(line: str, name: str) -> bool:
    return re.match(rf"^#{re.escape(name)}=", line) is not None


def parse_env(text: str) -> dict[str, str]:
    """`NAME=VALUE` as `deploy.sh` reads it: the last assignment wins, one matching pair of quotes is dropped."""
    values: dict[str, str] = {}
    for line in text.splitlines():
        match = re.match(r"^[ \t]*(?:export[ \t]+)?([A-Z][A-Z0-9_]*)=(.*)$", line)
        if not match:
            continue
        value = match.group(2)
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[match.group(1)] = value
    return values


def set_value(text: str, name: str, value: str) -> str:
    """The text with `NAME` set: the last live assignment is replaced, else the value goes after the last template line
    (`#NAME=...`), else at the end. Every other byte is untouched."""
    lines = text.split("\n")
    live = [i for i, line in enumerate(lines) if _line_assigns(line, name)]
    if live:
        lines[live[-1]] = f"{name}={value}"
        return "\n".join(lines)
    templates = [i for i, line in enumerate(lines) if _line_templates(line, name)]
    if templates:
        lines.insert(templates[-1] + 1, f"{name}={value}")
        return "\n".join(lines)
    suffix = "" if text.endswith("\n") or not text else "\n"
    return text + suffix + f"{name}={value}\n"


def example_names(example_text: str) -> set[str]:
    """Every name the example mentions, live or as a `#NAME=` template."""
    return {m.group(1) for m in re.finditer(r"^#?[ \t]*(?:export[ \t]+)?([A-Z][A-Z0-9_]*)=", example_text, re.M)}


# --------------------------------------------------------------------------------------------------------- create


def derive_names(instance: str) -> dict[str, str]:
    if not INSTANCE_PATTERN.fullmatch(instance):
        raise ValueError("the instance name is 3 to 40 characters of a-z, 0-9 and '-', starting with a letter")
    slug = instance.replace("-", "_")
    return {
        "ALPHA_INSTANCE": instance,
        "POSTGRES_DB": slug,
        "POSTGRES_USER": f"{slug}_owner",
        "ALPHA_APP_DB_USER": f"{slug}_app",
        "S3_BUCKET": instance,
        "NEXT_PUBLIC_INSTANCE_LABEL": instance,
    }


def generate_values(instance: str, http_port: int, date: str) -> tuple[dict[str, str], str]:
    """Every value `alpha.env` gets, plus the private ring line for `provider.env`. Fresh randomness on every call."""
    if not 1 <= http_port <= 65535:
        raise ValueError("the http port is a port number")
    values = derive_names(instance)
    pg_password = secrets.token_hex(24)
    app_password = secrets.token_hex(24)
    minio_user = "m" + secrets.token_hex(8)
    minio_password = secrets.token_hex(24)
    private, public = new_key_pair()
    kid = f"k{date}"
    if not KID_PATTERN.fullmatch(kid):
        raise ValueError("the key id date is plain digits")
    values.update({
        "ALPHA_HTTP_PORT": str(http_port),
        "POSTGRES_PASSWORD": pg_password,
        "ALPHA_APP_DB_PASSWORD": app_password,
        "MINIO_ROOT_USER": minio_user,
        "MINIO_ROOT_PASSWORD": minio_password,
        "S3_ACCESS_KEY_ID": minio_user,
        "S3_SECRET_ACCESS_KEY": minio_password,
        "DATABASE_URL": f"postgresql+psycopg://{values['ALPHA_APP_DB_USER']}:{app_password}@postgres:5432/{values['POSTGRES_DB']}",
        "MIGRATOR_DATABASE_URL": f"postgresql+psycopg://{values['POSTGRES_USER']}:{pg_password}@postgres:5432/{values['POSTGRES_DB']}",
        "AUDITMANAGER_API_TOKEN": secrets.token_urlsafe(32),
        "AUDITMANAGER_PROVIDER_MODE": "live",
        "AUDITMANAGER_PROVIDER_SOURCE": "database",
        "AUDITMANAGER_SECRETS_PUBLIC_KEYS": f"{kid}:{base64.b64encode(public).decode()}",
        "AUDITMANAGER_SECRETS_ACTIVE_KID": kid,
    })
    return values, f"{kid}:{base64.b64encode(private).decode()}"


def render_alpha(example_text: str, values: Mapping[str, str], extra: Mapping[str, str]) -> str:
    text = example_text
    for name, value in values.items():
        text = set_value(text, name, value)
    for name, value in extra.items():
        text = set_value(text, name, value)
    return text


def render_provider(example_text: str, private_ring: str) -> str:
    return set_value(example_text, "AUDITMANAGER_SECRETS_KEYS", private_ring)


def _write_new(path: Path, content: str) -> bool:
    """Create `path` with mode 600 holding `content`, or change nothing: False when it is already there. A hard link from a
    temporary file in the same directory is the one operation that fails rather than replaces."""
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=str(path.parent))
    try:
        os.fchmod(descriptor, 0o600)
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(content)
        try:
            os.link(temporary, path)
        except FileExistsError:
            return False
        return True
    finally:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass


def create(env_dir: Path, instance: str, http_port: int, extra: Mapping[str, str], *, date: str | None = None) -> str:
    """Create both files. Returns `created`, or `exists` when `alpha.env` is already there (and nothing was touched).

    Raises `ValueError` when the request is refused, with a message that names no value."""
    alpha, provider = env_dir / "alpha.env", env_dir / "provider.env"
    example_alpha = (env_dir / "alpha.env.example").read_text(encoding="utf-8")
    example_provider = (env_dir / "provider.env.example").read_text(encoding="utf-8")
    known = example_names(example_alpha)
    for name, value in extra.items():
        if not NAME_PATTERN.fullmatch(name) or name not in known:
            raise ValueError(f"--set {name}: not a name alpha.env.example mentions")
        if name in GENERATED_NAMES:
            raise ValueError(f"--set {name}: generated by this installer; it cannot be set by hand")
        if not SET_VALUE_PATTERN.fullmatch(value):
            raise ValueError(f"--set {name}: the value holds a character other than letters, digits and ._:/@,=+-")
    if alpha.exists() or alpha.is_symlink():
        return "exists"
    if provider.exists() or provider.is_symlink():
        raise ValueError(
            "provider.env exists but alpha.env does not: a half-written install; nothing was changed")
    values, private_ring = generate_values(instance, http_port, date or time.strftime("%Y%m%d", time.gmtime()))
    alpha_text = render_alpha(example_alpha, values, extra)
    provider_text = render_provider(example_provider, private_ring)
    # The private ring first: an alpha.env without its provider.env is the state that cannot be repaired by a rerun.
    if not _write_new(provider, provider_text):
        raise ValueError("provider.env appeared while this ran; nothing else was changed")
    if not _write_new(alpha, alpha_text):
        return "exists"
    return "created"


# ---------------------------------------------------------------------------------------------------------- check


def check(env: Path, provider: Path | None, example: Path) -> list[str]:
    """The problems of an existing `alpha.env` (and `provider.env`), as sentences that name variables and never values."""
    problems: list[str] = []
    try:
        text = env.read_text(encoding="utf-8")
    except OSError:
        return [f"{env.name} cannot be read"]
    values = parse_env(text)
    example_values = parse_env(example.read_text(encoding="utf-8")) if example.exists() else {}
    for name in REQUIRED_NAMES:
        if not values.get(name):
            problems.append(f"{name} is not set")
    if problems:
        return problems
    for name in PLACEHOLDER_NAMES:
        if example_values.get(name) and values[name] == example_values[name]:
            problems.append(f"{name} is still the value published in alpha.env.example")
    if example_values.get("POSTGRES_PASSWORD") == values["POSTGRES_PASSWORD"]:
        problems.append("POSTGRES_PASSWORD is still the example's")
    if not INSTANCE_PATTERN.fullmatch(values["ALPHA_INSTANCE"]):
        problems.append("ALPHA_INSTANCE is not a name of lower-case letters, digits and '-'")
    if not ROLE_PATTERN.fullmatch(values["ALPHA_APP_DB_USER"]):
        problems.append("ALPHA_APP_DB_USER is not a role name of a-z, 0-9 and _")
    if values["ALPHA_APP_DB_USER"] == values["POSTGRES_USER"]:
        problems.append("ALPHA_APP_DB_USER is the owner role")
    if not APP_PASSWORD_PATTERN.fullmatch(values["ALPHA_APP_DB_PASSWORD"]):
        problems.append("ALPHA_APP_DB_PASSWORD is not 20 to 128 characters of A-Z a-z 0-9 . _ ~ -")
    if values["ALPHA_APP_DB_PASSWORD"] == values["POSTGRES_PASSWORD"]:
        problems.append("ALPHA_APP_DB_PASSWORD equals POSTGRES_PASSWORD")
    migrator = URL_PATTERN.match(values["MIGRATOR_DATABASE_URL"])
    application = URL_PATTERN.match(values["DATABASE_URL"])
    if not migrator:
        problems.append("MIGRATOR_DATABASE_URL does not parse as postgresql+psycopg://user:password@host:port/db")
    elif (migrator.group(1), migrator.group(2), migrator.group(5)) != (
            values["POSTGRES_USER"], values["POSTGRES_PASSWORD"], values["POSTGRES_DB"]):
        problems.append("MIGRATOR_DATABASE_URL does not carry POSTGRES_USER, POSTGRES_PASSWORD and POSTGRES_DB")
    if not application:
        problems.append("DATABASE_URL does not parse as postgresql+psycopg://user:password@host:port/db")
    elif (application.group(1), application.group(2), application.group(5)) != (
            values["ALPHA_APP_DB_USER"], values["ALPHA_APP_DB_PASSWORD"], values["POSTGRES_DB"]):
        problems.append("DATABASE_URL does not carry ALPHA_APP_DB_USER, ALPHA_APP_DB_PASSWORD and POSTGRES_DB")
    if values["S3_ACCESS_KEY_ID"] != values["MINIO_ROOT_USER"]:
        problems.append("S3_ACCESS_KEY_ID does not match MINIO_ROOT_USER")
    if values["S3_SECRET_ACCESS_KEY"] != values["MINIO_ROOT_PASSWORD"]:
        problems.append("S3_SECRET_ACCESS_KEY does not match MINIO_ROOT_PASSWORD")
    if len(values["MINIO_ROOT_PASSWORD"]) < 8:
        problems.append("MINIO_ROOT_PASSWORD is shorter than MinIO's minimum of 8 characters")
    source = values.get("AUDITMANAGER_PROVIDER_SOURCE", "") or "environment"
    if source == "database":
        if values["AUDITMANAGER_PROVIDER_MODE"] != "live":
            problems.append("AUDITMANAGER_PROVIDER_SOURCE is database and AUDITMANAGER_PROVIDER_MODE is not live")
        problems.extend(_check_key_ring(values, provider))
    return problems


def _check_key_ring(values: Mapping[str, str], provider: Path | None) -> list[str]:
    public_ring = values.get("AUDITMANAGER_SECRETS_PUBLIC_KEYS", "")
    kid = values.get("AUDITMANAGER_SECRETS_ACTIVE_KID", "")
    if not public_ring or not kid:
        return ["AUDITMANAGER_SECRETS_PUBLIC_KEYS and AUDITMANAGER_SECRETS_ACTIVE_KID are not set (the source is database)"]
    if provider is None or not provider.exists():
        return ["provider.env is missing (the source is database: the worker needs AUDITMANAGER_SECRETS_KEYS)"]
    private_ring = parse_env(provider.read_text(encoding="utf-8")).get("AUDITMANAGER_SECRETS_KEYS", "")
    if not private_ring:
        return ["AUDITMANAGER_SECRETS_KEYS is not set in provider.env (the source is database)"]
    public = _ring(public_ring)
    private = _ring(private_ring)
    if public is None or private is None:
        return ["a key ring is not <kid>:<base64 of 32 bytes>[,...]"]
    if kid not in public or kid not in private:
        return ["AUDITMANAGER_SECRETS_ACTIVE_KID is not in both key rings"]
    if x25519_public(private[kid]) != public[kid]:
        return ["the public key in alpha.env is not the pair of the private key in provider.env"]
    return []


def _ring(raw: str) -> dict[str, bytes] | None:
    ring: dict[str, bytes] = {}
    for item in (part for part in raw.split(",") if part.strip()):
        kid, separator, encoded = item.strip().partition(":")
        if not separator or not KID_PATTERN.fullmatch(kid):
            return None
        try:
            key = base64.b64decode(encoded.strip(), validate=True)
        except ValueError:
            return None
        if len(key) != 32 or kid in ring:
            return None
        ring[kid] = key
    return ring


# ----------------------------------------------------------------------------------------------------- command line


def _parse_assignments(items: Sequence[str]) -> dict[str, str]:
    result: dict[str, str] = {}
    for item in items:
        name, separator, value = item.partition("=")
        if not separator or not NAME_PATTERN.fullmatch(name):
            raise ValueError(f"{item.split('=')[0]!r} is not NAME=VALUE")
        result[name] = value
    return result


def _cmd_create(args: argparse.Namespace) -> int:
    try:
        extra = _parse_assignments(args.set or [])
        outcome = create(Path(args.env_dir), args.instance, args.http_port, extra)
    except (ValueError, OSError) as error:
        print(f"first_install_env: {error}")
        return 3
    if outcome == "exists":
        print("first_install_env: alpha.env already exists; nothing was written")
        return 4
    print("first_install_env: created alpha.env and provider.env (mode 600); no value is printed")
    return 0


def _cmd_check(args: argparse.Namespace) -> int:
    env = Path(args.env)
    provider = Path(args.provider) if args.provider else None
    problems = check(env, provider, Path(args.example))
    mode = stat.S_IMODE(env.stat().st_mode) if env.exists() else 0
    if mode & 0o077:
        problems.append(f"{env.name} is readable by others (mode {mode:o}); it must be 600")
    if provider is not None and provider.exists() and stat.S_IMODE(provider.stat().st_mode) & 0o077:
        problems.append(f"{provider.name} is readable by others; it must be 600")
    for problem in problems:
        print(problem)
    return 3 if problems else 0


def _cmd_get(args: argparse.Namespace) -> int:
    if args.name not in READABLE_NAMES:
        print(f"first_install_env: {args.name} is not one of the names this command prints", file=sys.stderr)
        return 2
    values = parse_env(Path(args.env).read_text(encoding="utf-8"))
    print(values.get(args.name, ""))
    return 0


def _cmd_set(args: argparse.Namespace) -> int:
    path = Path(args.env)
    try:
        assignments = _parse_assignments(args.assignments)
        for name, value in assignments.items():
            if not SET_VALUE_PATTERN.fullmatch(value):
                raise ValueError(f"{name}: the value holds a character other than letters, digits and ._:/@,=+-")
        text = path.read_text(encoding="utf-8")
        mode = stat.S_IMODE(path.stat().st_mode)
    except (ValueError, OSError) as error:
        print(f"first_install_env: {error}")
        return 3
    for name, value in assignments.items():
        text = set_value(text, name, value)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=str(path.parent))
    try:
        os.fchmod(descriptor, mode)
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise
    print("first_install_env: set " + ", ".join(sorted(assignments)))
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="first_install_env.py", description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    p_create = sub.add_parser("create")
    p_create.add_argument("--env-dir", required=True)
    p_create.add_argument("--instance", required=True)
    p_create.add_argument("--http-port", required=True, type=int)
    p_create.add_argument("--set", action="append", metavar="NAME=VALUE")
    p_create.set_defaults(handler=_cmd_create)
    p_check = sub.add_parser("check")
    p_check.add_argument("--env", required=True)
    p_check.add_argument("--provider")
    p_check.add_argument("--example", required=True)
    p_check.set_defaults(handler=_cmd_check)
    p_get = sub.add_parser("get")
    p_get.add_argument("--env", required=True)
    p_get.add_argument("name")
    p_get.set_defaults(handler=_cmd_get)
    p_set = sub.add_parser("set")
    p_set.add_argument("--env", required=True)
