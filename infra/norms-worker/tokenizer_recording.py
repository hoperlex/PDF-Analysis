"""Record a fast tokenizer's answers, and replay them without the tokenizer.

The windowing (``auditmanager.norms.embedding.windowing``) asks a tokenizer three things:
``tokenizer(text, add_special_tokens=False, return_offsets_mapping=True, truncation=False)``,
``tokenizer.encode(text, add_special_tokens=True, truncation=False)`` (only its length is
used) and ``num_special_tokens_to_add(pair=False)``. :class:`RecordingTokenizer` wraps the
real tokenizer inside the norms-worker image and keeps every answer; :class:`ReplayTokenizer`
answers from a recording in a test with no model runtime at all, and raises
:class:`RecordingMiss` on any question the recording does not hold. A port that asked a
different question than the runner it was recorded against therefore fails, rather than
being answered by a guess.

Format ``auditmanager-tokenizer-recording/1``::

    {"format": ..., "source": "<tokenizer identity>", "limit": 512, "overlap": 64,
     "special_tokens": 2, "text_sha256": ["<sha256 of each synthetic text>", ...],
     "offsets": {"<sha256 of text>": [start0, end0, start1, end1, ...]},
     "encode_lengths": {"<sha256 of text>": n}}

The texts themselves are not stored: they are :func:`synthetic_texts`, regenerated by the
reader and checked against ``text_sha256``.

Standard library only: the image-contract test and the container-free windowing tests load it.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

RECORDING_FORMAT = "auditmanager-tokenizer-recording/1"


class RecordingMiss(KeyError):
    """The replayed tokenizer was asked something the recording does not hold."""


def _key(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


class RecordingTokenizer:
    """Forward to ``inner`` and keep every answer the windowing reads."""

    is_fast = True

    def __init__(self, inner: Any) -> None:
        if not getattr(inner, "is_fast", False):
            raise ValueError("only a fast tokenizer can be recorded")
        self._inner = inner
        self.offsets: dict[str, list[int]] = {}
        self.encode_lengths: dict[str, int] = {}
        self.special_tokens = int(inner.num_special_tokens_to_add(pair=False))

    def __call__(self, text: str, **kwargs: Any) -> dict[str, Any]:
        result = self._inner(text, **kwargs)
        self.offsets[_key(text)] = [int(value) for pair in result["offset_mapping"] for value in pair]
        return result

    def encode(self, text: str, **kwargs: Any) -> list[int]:
        result = self._inner.encode(text, **kwargs)
        self.encode_lengths[_key(text)] = len(result)
        return result

    def num_special_tokens_to_add(self, pair: bool = False) -> int:
        return int(self._inner.num_special_tokens_to_add(pair=pair))

    def document(self, *, source: str, texts: list[str], limit: int, overlap: int) -> dict[str, Any]:
        return {
            "format": RECORDING_FORMAT,
            "source": source,
            "limit": limit,
            "overlap": overlap,
            "special_tokens": self.special_tokens,
            "text_sha256": [_key(text) for text in texts],
            "offsets": dict(sorted(self.offsets.items())),
            "encode_lengths": dict(sorted(self.encode_lengths.items())),
        }


class ReplayTokenizer:
    """Answer exactly what a recording holds; log every question asked."""

    is_fast = True

    def __init__(self, recording: dict[str, Any]) -> None:
        if recording.get("format") != RECORDING_FORMAT:
            raise ValueError(f"not a {RECORDING_FORMAT} recording")
        self._offsets = recording["offsets"]
        self._encode_lengths = recording["encode_lengths"]
        self._special_tokens = int(recording["special_tokens"])
        self.questions: list[tuple[str, str]] = []

    def __call__(
        self,
        text: str,
        *,
        add_special_tokens: bool,
        return_offsets_mapping: bool,
        truncation: bool,
    ) -> dict[str, Any]:
        if add_special_tokens or not return_offsets_mapping or truncation:
            raise RecordingMiss("only the offsets question without special tokens was recorded")
        key = _key(text)
        self.questions.append(("offsets", key))
        if key not in self._offsets:
            raise RecordingMiss(f"offsets of text {key[:12]} were not recorded")
        flat = self._offsets[key]
        offsets = [(flat[index], flat[index + 1]) for index in range(0, len(flat), 2)]
        return {"input_ids": list(range(len(offsets))), "offset_mapping": offsets}

    def encode(self, text: str, *, add_special_tokens: bool, truncation: bool) -> list[int]:
        if not add_special_tokens or truncation:
            raise RecordingMiss("only encode with special tokens and no truncation was recorded")
        key = _key(text)
        self.questions.append(("encode", key))
        if key not in self._encode_lengths:
            raise RecordingMiss(f"encode length of text {key[:12]} was not recorded")
        return [0] * int(self._encode_lengths[key])

    def num_special_tokens_to_add(self, pair: bool = False) -> int:
        if pair:
            raise RecordingMiss("pair special tokens were not recorded")
        return self._special_tokens


def load_recording(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def write_recording(path: Path, document: dict[str, Any]) -> None:
    path.write_text(
        json.dumps(document, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n",
        encoding="utf-8",
    )


# --- the synthetic text set both recordings are made over ----------------------------------

_WORDS = (
    "здание", "помещение", "эвакуационный", "выход", "ширина", "высота", "лестничный", "марш",
    "ограждение", "предел", "огнестойкости", "противопожарная", "преграда", "вентиляция",
    "дымоудаление", "маломобильных", "групп", "населения", "ёмкость", "приёмка", "чертёж",
    "СП", "ГОСТ", "СНиП", "ВСН", "РФ", "м²", "м³", "кПа", "°C", "±0,5", "№", "«норма»",
    "не", "менее", "более", "должна", "быть", "допускается", "следует", "при", "для", "и",
)
_SHAPES = (
    "{n}.{m}. ",
    "| {n} | {w} | {m},{k} МПа |",
    "ГОСТ_{n:05d}-2026__{w}_{w}.pdf",
    "...",
    "(п. {n}.{m}.{k})",
    "REI {n}0",
    "«{w}»",
    "{w}-{w}",
)


def _stream(seed: str):
    counter = 0
    while True:
        block = hashlib.sha256(f"{seed}:{counter}".encode()).digest()
        counter += 1
        yield from block


def synthetic_texts() -> list[str]:
    """Twenty-four deterministic Russian normative-style texts, 40 to about 7 000 characters.

    No corpus text: a recording is committed to git, and the corpus never is. Sizes are chosen
    so that roughly half need more than one 512-token window under the real tokenizer.
    """
    texts = []
    for index in range(24):
        stream = _stream(f"norms-worker-synthetic-{index}")
        target = 40 + (index * index * 12)
        parts: list[str] = []
        length = 0
        while length < target:
            if next(stream) % 4 == 0:
                shape = _SHAPES[next(stream) % len(_SHAPES)]
                part = shape.format(
                    n=next(stream) % 40 + 1,
                    m=next(stream) % 12 + 1,
                    k=next(stream) % 10,
                    w=_WORDS[next(stream) % len(_WORDS)],
                )
            else:
                part = _WORDS[next(stream) % len(_WORDS)]
            parts.append(part)
            length += len(part) + 1
        texts.append(" ".join(parts).strip())
    return texts
