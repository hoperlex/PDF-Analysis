#!/usr/bin/env python3
"""Build or byte-check the synthetic AR v2 PDF portal bundles.

Only source-controlled text, a committed font and deterministic PDF/ZIP writers
are inputs. No provider, clock, network service or customer document is read.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

FIXTURES_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = FIXTURES_ROOT.parents[1]
sys.path.insert(0, str(FIXTURES_ROOT))

from ar_corpus import document, pdfextract  # noqa: E402
from build_ar_corpus import load_font  # noqa: E402
from portal_bundle import bundle  # noqa: E402
from portal_bundle.pdffacts import read_pages  # noqa: E402
from seeded import cases, validate  # noqa: E402

OUT = REPO_ROOT / "fixtures" / "evaluation" / "ar_v2"
BUNDLE_COUNT = 10
PAGE_X = 54.0
FONT_SIZE = 10.5
RECOGNISED_ONLY_DECOY = "Распознанный текст: фиктивная площадь 999 м2."


class SeedError(RuntimeError):
    """A synthetic source or generated byte failed its own oracle."""


def _json(data: object) -> bytes:
    return (json.dumps(data, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _placements(lines: list[str], font) -> list[tuple[str, float, float, float]]:
    if len(lines) > 28:
        raise SeedError("a page exceeds its fixed line budget")
    placed = []
    for index, line in enumerate(lines):
        if font.text_width(line, FONT_SIZE) > document.PAGE_WIDTH - 2 * PAGE_X:
            raise SeedError(f"a line exceeds the PDF text box: {line!r}")
        placed.append((line, FONT_SIZE, PAGE_X, 780.0 - index * 23.0))
    return placed


def build(
    *, profile: str = cases.PROFILE,
    categories: tuple[str, ...] = cases.CATEGORIES,
    control_archetype: str = "near_miss",
) -> dict[str, bytes]:
    """Generate a complete or selected-category byte map in memory."""
    if profile != cases.PROFILE:
        raise SeedError(f"unknown analysis profile: {profile}")
    if control_archetype != "near_miss":
        raise SeedError(f"unknown control archetype: {control_archetype}")
    if not categories or len(set(categories)) != len(categories) or set(categories) - set(cases.CATEGORIES):
        raise SeedError("categories must be distinct members of the sealed AR v2 vocabulary")

    chosen = set(categories)
    issue_specs = [issue for issue in cases.ISSUES if issue.category in chosen]
    control_specs = [control for control in cases.CONTROLS if control.category in chosen]
    font = load_font()
    output: dict[str, bytes] = {}
    entries: list[dict] = []
    issues: list[dict] = []
    controls: list[dict] = []

    for number in range(BUNDLE_COUNT):
        stem = f"ar_v2_{number + 1:02d}"
        page_lines = [
            [f"Синтетический комплект {stem}.", "Лист АР-01: текст проекта."],
            [f"Синтетический комплект {stem}.", "Лист АР-02: текст проекта."],
        ]
        for index, issue in enumerate(cases.ISSUES):
            if index % BUNDLE_COUNT != number or issue.category not in chosen:
                continue
            evidence = []
            for statement_index, quote in enumerate(issue.statements):
                page = min(statement_index, 1)
                page_lines[page].append(quote)
                evidence.append({"page": page + 1, "quote": quote})
            item = {
                "id": issue.id, "bundle_id": stem, "category": issue.category,
                "archetype": issue.archetype, "evidence": evidence,
            }
            if issue.missing_content is not None:
                item["missing_content"] = issue.missing_content
            issues.append(item)
        for index, control in enumerate(cases.CONTROLS):
            if index != number or control.category not in chosen:
                continue
            page_lines[0].append(control.statement)
            controls.append({
                "id": control.id, "bundle_id": stem, "category": control.category,
                "archetype": control.archetype, "control_archetype": control_archetype,
                "scope": control.scope, "why_not_issue": control.why_not_issue,
                "expected_finding": False,
                "evidence": [{"page": 1, "quote": control.statement}],
            })
        pdf = document.simple_text_pdf(font, [_placements(lines, font) for lines in page_lines])
        pages = pdfextract.extract_pages(pdf)
        if len(pages) != 2:
            raise SeedError(f"{stem}: extracted {len(pages)} pages, expected 2")
        page_facts = read_pages(pdf)
        if number == 0:
            # Deliberately present only in portal recognition, never in the PDF
            # text layer. A downstream matcher must not cite this string.
            blocks = bundle.text_blocks(
                page_facts,
                bodies={0: page_facts[0].text + "\n" + RECOGNISED_ONLY_DECOY},
            )
            portal_files = bundle.make_files(pdf, stem, pages=page_facts, blocks=blocks)
        else:
            portal_files = bundle.make_files(pdf, stem, pages=page_facts)
        archive = bundle.build_bundle(portal_files).data
        pdf_path = f"bundles/{stem}.pdf"
        archive_path = f"bundles/{stem}.zip"
        output[pdf_path] = pdf
        output[archive_path] = archive
        entries.append({
            "id": stem, "pdf": pdf_path, "portal_bundle": archive_path,
            "page_count": 2, "supplied_headers": ["Лист АР-01", "Лист АР-02"],
            "pdf_sha256": _sha(pdf), "portal_bundle_sha256": _sha(archive),
        })

    manifest = {
        "schema": "ar-v2-seeded/1", "profile": profile, "source": "synthetic",
        "bundles": entries, "issues": issues, "controls": controls,
    }
    output["expected_issues.json"] = _json(manifest)
    validate.validate_bytes(manifest, output, require_full=(chosen == set(cases.CATEGORIES)))
    return output


def check_or_write(*, check: bool) -> None:
    first = build()
    second = build()
    if first != second:
        raise SeedError("two in-memory generations differ")
    if check:
        actual = {
            str(path.relative_to(OUT)): path.read_bytes()
            for path in OUT.rglob("*") if path.is_file()
        } if OUT.is_dir() else {}
        if first != actual:
            missing = sorted(first.keys() - actual.keys())
            extra = sorted(actual.keys() - first.keys())
            changed = sorted(name for name in first.keys() & actual.keys() if first[name] != actual[name])
            raise SeedError(f"committed corpus differs: missing={missing}, extra={extra}, changed={changed}")
        validate.validate_bytes(json.loads(actual["expected_issues.json"]), actual, require_full=True)
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, data in first.items():
            path = OUT / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f"AR v2 seeded corpus OK: {BUNDLE_COUNT} bundles, {len(cases.ISSUES)} issues, {len(cases.CONTROLS)} controls")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare committed bytes with two builds")
    args = parser.parse_args()
    check_or_write(check=args.check)
