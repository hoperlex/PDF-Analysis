    # lamps: a 3 x 3 m grid in every room except the stairs
    lamps = 0
    for room in FLOOR1:
        if room.name.startswith("Лестничная"):
            continue
        nx = max(1, round((room.x1 - room.x0) / 3))
        ny = max(1, round((room.y1 - room.y0) / 3))
        for i in range(nx):
            for j in range(ny):
                mx = room.x0 + (room.x1 - room.x0) * (i + 0.5) / nx
                my = room.y0 + (room.y1 - room.y0) * (j + 0.5) / ny
