def build_all(scratch: Path) -> tuple[list[tuple[Path, bytes]], str]:
    """Build every artefact, verifying every invariant before returning anything."""
    font = load_font()

    problems = verify_filler_is_inert()
    if problems:
        raise BuildError(
            "filler prose is not inert, so the corpus would seed an issue nobody "
            "declared:\n  " + "\n  ".join(problems)
        )

    problems = verify_source_placement()
    if problems:
        raise BuildError("quotation placement:\n  " + "\n  ".join(problems))

    problems = verify_quotations_unique()
    if problems:
        raise BuildError("quotation uniqueness:\n  " + "\n  ".join(problems))

    artefacts: list[tuple[Path, bytes]] = []
    records: list[dict[str, object]] = []
    independent_reader = ""
    failures: list[str] = []

    for doc in content.DOCUMENTS:
        data = layout.build(doc, font)
        pages = pdfextract.extract_pages(data)
        failures += verify_extracted(doc, pages, "ar_corpus.pdfextract")
        other_pages, reader = independent_pages(data, scratch)
        independent_reader = reader
        failures += verify_extracted(doc, other_pages, reader)
        failures += verify_envelope(doc.label, data)
        records.append(_document_record(doc, data, pages))
        artefacts.append((DOC_DIR / doc.filename, data))

    if failures:
        raise BuildError(
            "the text layer does not carry the manifest quotations:\n  "
            + "\n  ".join(failures)
        )

    fixtures = negatives.build_all(font)
    problems = verify_negatives(fixtures)
    if problems:
        raise BuildError("negative fixtures:\n  " + "\n  ".join(problems))

    problems = verify_composition(fixtures)
    if problems:
        raise BuildError("corpus composition:\n  " + "\n  ".join(problems))

    manifest = build_manifest(records, fixtures, independent_reader)
    artefacts.append((OUT_DIR / MANIFEST_NAME, manifest_bytes(manifest)))
    artefacts += [(NEGATIVE_DIR / f.filename, f.data) for f in fixtures]

    checksums = checksum_bytes([
        (str(path.relative_to(OUT_DIR)), data) for path, data in sorted(artefacts)
    ])
    artefacts.append((OUT_DIR / CHECKSUM_NAME, checksums))
    return artefacts, independent_reader


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build the PC-02 validation corpus.")
    parser.add_argument(
        "--check", action="store_true",
        help="verify the committed corpus against a fresh build; write nothing",
    )
    parser.add_argument(
        "--scratch", default=None,
        help="scratch directory for the independent extractor (default: a temp dir)",
    )
    args = parser.parse_args(argv)

    import tempfile

    with tempfile.TemporaryDirectory(prefix="pc02-build-") as tmp:
        scratch = Path(args.scratch) if args.scratch else Path(tmp)
        try:
            artefacts, reader = build_all(scratch)
        except (BuildError, ValueError, KeyError) as exc:
            print(f"FAIL: {exc}", file=sys.stderr)
            return 1

    if args.check:
        failures: list[str] = []
        for path, data in artefacts:
            rel = path.relative_to(REPO_ROOT)
            if not path.is_file():
                failures.append(f"{rel}: missing")
                continue
            committed = path.read_bytes()
            if committed != data:
                failures.append(
                    f"{rel}: committed sha256 {sha256(committed)} "
                    f"({len(committed)} bytes) != rebuilt sha256 {sha256(data)} "
                    f"({len(data)} bytes)"
                )
        if failures:
            print("FAIL: the committed corpus does not match a fresh build:",
                  file=sys.stderr)
            for failure in failures:
                print(f"  {failure}", file=sys.stderr)
            return 1
        print(f"OK  {len(artefacts)} artefacts match a fresh build "
              f"(independent extractor: {reader})")
        return 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    DOC_DIR.mkdir(parents=True, exist_ok=True)
    NEGATIVE_DIR.mkdir(parents=True, exist_ok=True)
    for path, data in artefacts:
        path.write_bytes(data)
        print(f"wrote {path.relative_to(REPO_ROOT)}  {sha256(data)}  {len(data)} bytes")
    print(f"independent extractor: {reader}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
