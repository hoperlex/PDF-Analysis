def independent_pages(data: bytes, scratch: Path) -> tuple[list[str], str]:
    """Extract page text with a reader that shares no code with the writer.

    Session A4's `pdfextract` and `pdfwrite` are separate modules, but they are one
    author's reading of one specification. If both were wrong in the same way, every
    quotation would verify and every downstream measurement would be contaminated
    silently - which is the failure mode this whole corpus exists to avoid. So the
    quotations are also resolved through `pdfplumber`, which is pinned in
    `docs/program/P02_LOCK.json`, and failing that through poppler's `pdftotext`.
    """
    try:
        import pdfplumber  # noqa: PLC0415
    except ImportError:
        pass
    else:
        scratch.mkdir(parents=True, exist_ok=True)
        tmp = scratch / "independent.pdf"
        tmp.write_bytes(data)
        with pdfplumber.open(str(tmp)) as pdf:
            return [page.extract_text() or "" for page in pdf.pages], "pdfplumber"

    scratch.mkdir(parents=True, exist_ok=True)
    tmp = scratch / "independent.pdf"
    txt = scratch / "independent.txt"
    tmp.write_bytes(data)
    result = subprocess.run(
        ["pdftotext", "-enc", "UTF-8", str(tmp), str(txt)],
        capture_output=True, check=False,
    )
    if result.returncode != 0:
        raise BuildError(
            "no independent extractor is available: pdfplumber is not importable and "
            f"pdftotext failed ({result.returncode}). The corpus may not be written "
            "without a second reader, because a quotation verified only by the "
            "extractor its own author wrote is not verified."
        )
    return txt.read_text(encoding="utf-8").split("\f")[:-1], "pdftotext"


