#!/usr/bin/env python3
"""Build the PC-02 field-validation corpus and its ground-truth manifest.

    python3 fixtures/validation/PC-02/build_pc02_corpus.py           # write the corpus
    python3 fixtures/validation/PC-02/build_pc02_corpus.py --check   # verify, write none

`--check` rebuilds every artefact in memory and compares it byte-for-byte with what is
committed, then re-runs every oracle assertion *against the committed files* rather than
against the fresh build. Verifying the thing in your hand and verifying the thing on disk
are different claims, and only the second is what a validation session will consume.

What the build refuses to do - each of these is a guard, and each is shown failing by
`tools/validation/corpus_check.py --self-test`:

*   write if any filler line contains a digit or a placeholder token. This is the guard
    that keeps the ground truth honest. A stray number in boilerplate is a project
    attribute nobody declared, and a model that noticed it would be scored wrong for
    being right;
*   write if any line would overflow the text box or be drawn into the footer band,
    because a reader could then split or merge a quotation;
*   write if a quotation is not a substring of exactly one line on its declared page;
*   write if two quotations anywhere in the corpus are the same string;
*   write if a quotation is not recoverable character-for-character from the text
    extracted back out of the generated bytes, at exactly the pages it declares and no
    others - checked twice, once with the reference extractor and once with an extractor
    that shares no code with the writer;
*   write if a measurable document falls outside the PC-01 envelope;
*   write if a negative fixture violates anything other than the single rule it is named
    for, or if that rule was not actually evaluated;
*   write if the composition leaves the ranges the task fixes: 12-16 measurable
    documents, exactly 5 of them seeded, and 2-4 negative-envelope documents.

Pure standard library plus the already-pinned `pdfplumber` for the independent
cross-check. `docs/program/P02_LOCK.json` pins `pdfplumber` and `pypdf`; the root lock is
a single-writer hotspot this session does not own and nothing here adds to it.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[2]

# `ar_corpus` is session A4's stdlib PDF writer, TrueType subsetter and extractor. It is
# imported read-only: this task owns none of `tools/fixtures/**`.
sys.path.insert(0, str(REPO_ROOT / "tools" / "fixtures"))
sys.path.insert(0, str(HERE))

from ar_corpus import content as ar_content  # noqa: E402
from ar_corpus import envelope, pdfextract, pdfwrite, ttfsubset  # noqa: E402
from pc02_corpus import content, layout, negatives  # noqa: E402

FONT_ASSET = REPO_ROOT / "tools" / "fixtures" / "assets" / "ARCorpusSans.ttf"
OUT_DIR = REPO_ROOT / "fixtures" / "validation" / "PC-02"
DOC_DIR = OUT_DIR / "documents"
NEGATIVE_DIR = OUT_DIR / "negative"

MANIFEST_NAME = "corpus_manifest.json"
CHECKSUM_NAME = "SHA256SUMS"

MANIFEST_SCHEMA = "pc02-validation-corpus/1"

# The ranges task P4-QA-01 fixes. The seeded count is exact; the control count carries
# the whole range.
MIN_MEASURABLE = 12
MAX_MEASURABLE = 16
SEEDED_DOCUMENTS = 5
MIN_NEGATIVE = 2
MAX_NEGATIVE = 4

_DIGIT = re.compile(r"[0-9]")


class BuildError(RuntimeError):
    """An invariant the corpus is not allowed to be written without."""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def load_font() -> pdfwrite.EmbeddedFont:
    """Build the embedded font from the committed subset, never from a system font."""
    if not FONT_ASSET.is_file():
        raise BuildError(
            f"missing font subset {FONT_ASSET}. It is session A4's committed asset; "
            "this task does not rebuild it."
        )
    raw = FONT_ASSET.read_bytes()
    metrics = ttfsubset.read(raw)
    used = set(content.document_characters())
    outside = sorted(used - set(ar_content.REPERTOIRE))
    if outside:
        raise BuildError(
            "the PC-02 text uses characters outside the declared repertoire: "
            + " ".join(f"U+{ord(c):04X} {c!r}" for c in outside)
        )
    missing = sorted(used - set(metrics.char_to_gid))
    if missing:
        raise BuildError(
            f"the committed font subset has no glyph for {''.join(missing)!r}."
        )
    return pdfwrite.EmbeddedFont(
        font_bytes=raw,
        units_per_em=metrics.units_per_em,
        char_to_gid=metrics.char_to_gid,
        gid_advance=metrics.gid_advance,
        ascent=metrics.ascent,
        descent=metrics.descent,
        cap_height=metrics.cap_height,
        bbox=metrics.bbox,
    )


