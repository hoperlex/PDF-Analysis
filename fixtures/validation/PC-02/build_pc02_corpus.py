# Guards
# --------------------------------------------------------------------------------------


def verify_filler_is_inert() -> list[str]:
    """No digit and no placeholder token in any line the corpus did not author as
    ground truth.

    This is the guard that stops the corpus seeding an issue by accident.
    """
    problems: list[str] = []
    for text in content.FILLER:
        if _DIGIT.search(text):
            problems.append(f"filler sentence contains a digit: {text!r}")
        for token in content.PLACEHOLDER_TOKENS:
            if token in text:
                problems.append(
                    f"filler sentence contains placeholder token {token!r}: {text!r}"
                )
    for doc in content.DOCUMENTS:
        for page in doc.pages:
            for line in page.lines:
                if line.role != "filler":
                    continue
                if _DIGIT.search(line.text):
                    problems.append(
                        f"{doc.label} page {page.number}: filler line contains a "
                        f"digit: {line.text!r}"
                    )
                for token in content.PLACEHOLDER_TOKENS:
                    if token in line.text:
                        problems.append(
                            f"{doc.label} page {page.number}: filler line contains "
                            f"placeholder token {token!r}: {line.text!r}"
                        )
    return problems


def verify_source_placement() -> list[str]:
    """Every quotation is a substring of exactly one authored line on its declared
    page."""
    problems: list[str] = []
    for doc in content.DOCUMENTS:
        for owner, page_number, quotation in content.all_quotations(doc):
            if not 1 <= page_number <= len(doc.pages):
                problems.append(
                    f"{owner}: declared page {page_number} is outside {doc.label}, "
                    f"which has {len(doc.pages)} pages"
                )
                continue
            page = doc.pages[page_number - 1]
            hits = [line.text for line in page.lines if quotation in line.text]
            if len(hits) != 1:
                problems.append(
                    f"{owner}: quotation {quotation!r} matches {len(hits)} authored "
                    f"lines on {doc.label} page {page_number}, expected exactly 1"
                )
    return problems


def verify_quotations_unique() -> list[str]:
    """No two ground-truth items anywhere in the corpus share a quotation string.

    Across documents this is not a correctness requirement - each document is analysed on
    its own - but it is an auditing one. A repeated string makes a session record
    ambiguous about which document a moderator was looking at, and two moderators have to
    produce comparable data.
    """
    seen: dict[str, str] = {}
    problems: list[str] = []
    for doc in content.DOCUMENTS:
        for owner, _page, quotation in content.all_quotations(doc):
            key = f"{doc.label}/{owner}"
            if quotation in seen and seen[quotation].split("/")[1] != owner:
                problems.append(
                    f"quotation {quotation!r} is claimed by both {seen[quotation]} "
                    f"and {key}"
                )
            seen.setdefault(quotation, key)
    return problems


def verify_extracted(doc: content.Doc, pages: list[str], reader: str) -> list[str]:
    """The load-bearing check: quotations survive the round trip through the PDF bytes.

    Character-for-character, at exactly the declared pages and nowhere else. The
    "nowhere else" half matters as much as the first: a quotation that also appeared on
    an undeclared page would make the grounding anchor ambiguous, and a finding could
    then be called grounded against a page nobody meant.
    """
    problems: list[str] = []
    if len(pages) != len(doc.pages):
        problems.append(
            f"{doc.label} [{reader}]: extracted {len(pages)} pages, the document "
            f"declares {len(doc.pages)}"
        )
        return problems

    declared: dict[str, set[int]] = {}
    for _owner, page_number, quotation in content.all_quotations(doc):
        declared.setdefault(quotation, set()).add(page_number)

    for quotation, declared_pages in sorted(declared.items()):
        found = {n for n, text in enumerate(pages, start=1) if quotation in text}
        if found != declared_pages:
            problems.append(
                f"{doc.label} [{reader}]: quotation {quotation!r} declared on pages "
                f"{sorted(declared_pages)}, found on pages {sorted(found)}"
            )
    return problems


def verify_envelope(label: str, data: bytes) -> list[str]:
    report = envelope.check(data)
    if report.accepted:
        return []
    return [
        f"{label} violates {r.rule} ({r.status.value}): {r.detail}"
        for r in report.results if r.status is not envelope.Status.PASS
    ]


def verify_negatives(fixtures: list[negatives.NegativeFixture]) -> list[str]:
    """Each negative violates exactly the single rule it is named for."""
    problems: list[str] = []
    for fixture in fixtures:
        report = envelope.check(fixture.data)
        if report.violations != (fixture.violates,):
            problems.append(
                f"{fixture.filename}: expected to violate exactly {fixture.violates}, "
                f"violates {list(report.violations)}"
            )
        if fixture.violates in report.not_evaluated:
            problems.append(
                f"{fixture.filename}: {fixture.violates} was not evaluated at all, so "
                "the fixture proves nothing about it"
            )
    return problems


def verify_composition(fixtures: list[negatives.NegativeFixture]) -> list[str]:
    """The counts the task fixes, asserted rather than assumed."""
    problems: list[str] = []
    measurable = content.DOCUMENTS
    seeded = content.seeded_documents()
    controls = content.control_documents()

    if not MIN_MEASURABLE <= len(measurable) <= MAX_MEASURABLE:
        problems.append(
            f"{len(measurable)} measurable documents, the task fixes "
            f"{MIN_MEASURABLE}-{MAX_MEASURABLE}"
        )
    if len(seeded) != SEEDED_DOCUMENTS:
        problems.append(
            f"{len(seeded)} seeded documents, the task fixes exactly {SEEDED_DOCUMENTS}"
        )
    if len(seeded) + len(controls) != len(measurable):
        problems.append("a measurable document is neither seeded nor a control")
    if not MIN_NEGATIVE <= len(fixtures) <= MAX_NEGATIVE:
        problems.append(
            f"{len(fixtures)} negative-envelope documents, the task fixes "
            f"{MIN_NEGATIVE}-{MAX_NEGATIVE}"
        )

    for doc in seeded:
        if not doc.seeded:
            problems.append(f"{doc.label} is marked seeded but carries no seeded issue")
    for doc in controls:
        if doc.seeded:
            problems.append(
                f"{doc.label} is marked a control but carries {len(doc.seeded)} seeded "
                "issue(s); a control document's findings are all false positives by "
                "construction, so a seeded issue in one would make that untrue"
            )
        if not doc.controls:
            problems.append(
                f"{doc.label} is a control document with no control statements, so it "
                "applies no false-positive pressure and measures nothing"
            )

    for doc in measurable:
        for issue in doc.seeded:
            if issue.category not in (
                content.CATEGORY_CONTRADICTION, content.CATEGORY_PLACEHOLDER
            ):
                problems.append(
                    f"{issue.id}: category {issue.category!r} is not one of the two "
                    "fixed by PROTOTYPE_PROFILE.md section 7.1"
                )
        for control in doc.controls:
            if control.archetype not in content.ARCHETYPES:
                problems.append(
                    f"{control.id}: archetype {control.archetype!r} is not declared"
                )
    return problems


