def _anchor(pages: list[str], page_number: int, quotation: str) -> dict[str, object]:
    """Locate a quotation inside the extracted page text, for the grounding gate."""
    text = pages[page_number - 1]
    offset = text.find(quotation)
    if offset < 0:
        raise BuildError(f"quotation {quotation!r} is not on page {page_number}")
    lines = text.split("\n")
    consumed = 0
    line_index = 0
    for index, line in enumerate(lines):
        if consumed <= offset < consumed + len(line) + 1:
            line_index = index
            break
        consumed += len(line) + 1
    return {
        "page": page_number,
        "quotation": quotation,
        "char_offset_in_page_text": offset,
        "line_index_in_page_text": line_index,
        "line_text": lines[line_index],
    }


def _document_record(doc: content.Doc, data: bytes,
                     pages: list[str]) -> dict[str, object]:
    return {
        "label": doc.label,
        "role": doc.role,
        "provenance": "synthetic",
        "path": f"fixtures/validation/PC-02/documents/{doc.filename}",
        "title_ru": doc.title,
        "summary_ru": doc.summary,
        "sha256": sha256(data),
        "bytes": len(data),
        "pages": len(pages),
        "language": "ru",
        "discipline": "AR",
        "page_text_sha256": [sha256(text.encode("utf-8")) for text in pages],
        "seeded_issue_count": len(doc.seeded),
        "seeded_issues": [
            {
                "id": issue.id,
                "category": issue.category,
                "attribute_ru": issue.attribute,
                "pages": sorted({ev.page for ev in issue.evidence}),
                "summary_ru": issue.summary,
                "why_seeded": issue.why_seeded,
                "evidence": [
                    _anchor(pages, ev.page, ev.quotation) for ev in issue.evidence
                ],
            }
            for issue in doc.seeded
        ],
        "control_count": len(doc.controls),
        "controls": [
            {
                "id": control.id,
                "pages": list(control.pages),
                "quotation": control.quotation,
                "archetype": control.archetype,
                "would_be_false_positive_as": control.would_be_false_positive_as,
                "why_not_an_issue_ru": control.why_not_an_issue,
                "anchors": [
                    _anchor(pages, page, control.quotation) for page in control.pages
                ],
            }
            for control in doc.controls
        ],
    }


def build_manifest(records: list[dict[str, object]],
                   fixtures: list[negatives.NegativeFixture],
                   independent_reader: str) -> dict[str, object]:
    seeded_issue_count = sum(int(r["seeded_issue_count"]) for r in records)
    control_count = sum(int(r["control_count"]) for r in records)
    archetypes_used = sorted({
        c["archetype"] for r in records for c in r["controls"]  # type: ignore[index]
    })
    return {
        "schema": MANIFEST_SCHEMA,
        "checkpoint": "PC-02",
        "task": "P4-QA-01",
        "synthetic": True,
        "notice": (
            "Synthetic corpus. No customer, production or real project bytes, and no "
            "real organisation, address, person or project. Owner decision OD-17 rules "
            "the corpus synthetic-only; every record's provenance is 'synthetic' and "
            "no record is 'anonymized'."
        ),
        "generated_by": "fixtures/validation/PC-02/build_pc02_corpus.py",
        "regenerate": "python3 fixtures/validation/PC-02/build_pc02_corpus.py",
        "verify": (
            ".venv/bin/python tools/validation/corpus_check.py "
            "fixtures/validation/PC-02/corpus_manifest.json"
        ),
        "protocol": "docs/program/validation/PC-02_PROTOCOL.md",
        "session_record_schema": "fixtures/validation/PC-02/session_record.schema.json",
        "text_extraction": (
            "Quotation offsets are into the text of a single page as produced by "
            "tools/fixtures/ar_corpus/pdfextract.py: runs grouped into lines by "
            "baseline, lines top to bottom, joined by a single newline. Every quotation "
            "lies wholly within one line, so any extractor that preserves line content "
            "resolves it identically. Every quotation was additionally resolved with "
            f"{independent_reader}, which shares no code with the writer."
        ),
        "independent_extractor": independent_reader,
        "envelope": {
            "max_bytes": envelope.MAX_BYTES,
            "max_pages": envelope.MAX_PAGES,
            "rules": {rule: envelope.RULE_DESCRIPTIONS[rule] for rule in envelope.RULES},
        },
        "composition": {
            "measurable_documents": len(records),
            "seeded_documents": SEEDED_DOCUMENTS,
            "control_documents": len(records) - SEEDED_DOCUMENTS,
            "seeded_issues": seeded_issue_count,
            "control_statements": control_count,
            "control_archetypes_used": len(archetypes_used),
            "negative_envelope_documents": len(fixtures),
            "note": (
                "Negative-envelope documents are counted separately and are excluded "
                "from every finding denominator and from every gate that counts "
                "measurable documents, G4 included."
            ),
        },
        "categories": [content.CATEGORY_CONTRADICTION, content.CATEGORY_PLACEHOLDER],
        "finding_labels": ["useful", "incorrect", "unclear"],
        "control_archetypes": content.ARCHETYPES,
        "documents": records,
        "negative_envelope_documents": [
            {
                "label": fixture.label,
                "provenance": "synthetic",
                "path": f"fixtures/validation/PC-02/negative/{fixture.filename}",
                "violates_rule": fixture.violates,
                "rule_description": envelope.RULE_DESCRIPTIONS[fixture.violates],
                "sha256": sha256(fixture.data),
                "bytes": len(fixture.data),
                "description_ru": fixture.description,
                "why_it_matters": fixture.why_it_matters,
            }
            for fixture in fixtures
        ],
    }


def manifest_bytes(manifest: dict[str, object]) -> bytes:
    return (
        json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=False) + "\n"
    ).encode("utf-8")


def checksum_bytes(entries: list[tuple[str, bytes]]) -> bytes:
    lines = [f"{sha256(data)}  {name}" for name, data in entries]
    return ("\n".join(lines) + "\n").encode("utf-8")


