def _create_blobs_and_manifest() -> None:
    op.execute(
        f"""
        CREATE TABLE blob (
            blob_id     text PRIMARY KEY,
            state       text NOT NULL DEFAULT 'temporary',
            sha256      text NULL,
            size_bytes  bigint NULL,
            media_type  text NULL,
            created_at  timestamptz NOT NULL DEFAULT now(),
            updated_at  timestamptz NOT NULL DEFAULT now(),
            CONSTRAINT ck_blob_blob_id_format CHECK ({id_check('blob_id', 'blob')}),
            CONSTRAINT ck_blob_state CHECK ({enum_check('state', BLOB_STATES)}),
            CONSTRAINT ck_blob_sha256 CHECK (sha256 IS NULL OR sha256 {SHA256}),
            CONSTRAINT ck_blob_size_bytes CHECK (size_bytes IS NULL OR size_bytes >= 0),
            CONSTRAINT ck_blob_available_is_verified CHECK (
                state <> 'available'
                OR (sha256 IS NOT NULL AND size_bytes IS NOT NULL AND media_type IS NOT NULL)
            )
        );
        """
    )
    # "Re-uploading identical content is idempotent by (sha256, size)". Scoped to
    # available bytes: a rejected or erased blob must not block a later good upload.
    op.execute(
        """
        CREATE UNIQUE INDEX uq_blob_available_content
            ON blob (sha256, size_bytes)
            WHERE state = 'available';
        """
    )
    op.execute(
        "COMMENT ON TABLE blob IS "
        "'Content metadata addressed only by blob_id. There is deliberately no bucket "
        "and no object-key column: the key layout is confined to the S3 adapter, and "
        "the contract lists a bucket name and an object key among the non-identities. "
        "A blob in temporary is never readable by business code and is referenced by "
        "no published manifest.';"
    )
    op.execute(
        "COMMENT ON COLUMN blob.sha256 IS "
        "'Verification value, never an identity and never a foreign key. Write-once: "
        "NULL until verification, then immutable.';"
    )

    op.execute(
        f"""
        CREATE TABLE input_manifest_entry (
            version_uid text NOT NULL REFERENCES document_version (version_uid),
            role        text NOT NULL,
            blob_id     text NOT NULL REFERENCES blob (blob_id),
            sha256      text NOT NULL,
            size_bytes  bigint NOT NULL,
            media_type  text NOT NULL,
            created_at  timestamptz NOT NULL DEFAULT now(),
            CONSTRAINT pk_input_manifest_entry PRIMARY KEY (version_uid, role),
            CONSTRAINT ck_input_manifest_entry_version_uid_format
                CHECK ({id_check('version_uid', 'ver')}),
            CONSTRAINT ck_input_manifest_entry_blob_id_format
                CHECK ({id_check('blob_id', 'blob')}),
            CONSTRAINT ck_input_manifest_entry_role
                CHECK (role ~ '^[a-z][a-z0-9_]*(\\.[a-z][a-z0-9_]*)*$'),
            CONSTRAINT ck_input_manifest_entry_sha256 CHECK (sha256 {SHA256}),
            CONSTRAINT ck_input_manifest_entry_size_bytes CHECK (size_bytes >= 0)
        );
        """
    )
    op.execute(
        "COMMENT ON TABLE input_manifest_entry IS "
        "'The immutable input manifest of one published version, one row per contract "
        "role. UPDATE and DELETE are refused by trigger: a published version and its "
        "manifest are frozen together, which is what makes a run reproducible against "
        "an exactly known input set.';"
    )


