# 8. The current-verdict projection
# ---------------------------------------------------------------------------


def _create_projection_view() -> None:
    # A view, not a table: "the current verdict is a rebuildable projection over the
    # event stream" is then true by construction, and the test that rebuilds it and
    # compares cannot pass by comparing a cache with itself.
    op.execute(
        """
        CREATE VIEW finding_current_verdict AS
        SELECT
            f.finding_uid,
            COALESCE(v.verdict, 'pending')  AS current_verdict,
            v.decision_id                   AS latest_verdict_decision_id,
            v.recorded_at                   AS latest_verdict_recorded_at,
            c.comment                       AS latest_comment,
            c.decision_id                   AS latest_comment_decision_id,
            l.decision_id                   AS latest_decision_id,
            l.recorded_at                   AS decision_recorded_at,
            COALESCE(n.event_count, 0)      AS decision_event_count
        FROM finding f
        LEFT JOIN LATERAL (
            SELECT e.decision_id, e.verdict, e.recorded_at
            FROM expert_decision_event e
            WHERE e.finding_uid = f.finding_uid AND e.verdict IS NOT NULL
            ORDER BY e.sequence_no DESC
            LIMIT 1
        ) v ON TRUE
        LEFT JOIN LATERAL (
            SELECT e.decision_id, e.comment
            FROM expert_decision_event e
            WHERE e.finding_uid = f.finding_uid AND e.comment IS NOT NULL
            ORDER BY e.sequence_no DESC
            LIMIT 1
        ) c ON TRUE
        LEFT JOIN LATERAL (
            SELECT e.decision_id, e.recorded_at
            FROM expert_decision_event e
            WHERE e.finding_uid = f.finding_uid
            ORDER BY e.sequence_no DESC
            LIMIT 1
        ) l ON TRUE
        LEFT JOIN LATERAL (
            SELECT count(*) AS event_count
            FROM expert_decision_event e
            WHERE e.finding_uid = f.finding_uid
        ) n ON TRUE;
        """
    )
    op.execute(
        "COMMENT ON VIEW finding_current_verdict IS "
        "'The PD-01 projection, defined once here so the API, the CSV and any test "
        "agree by construction. current_verdict is the verdict of the most recent "
        "verdict-bearing event and pending when there is none; a revoke moves it to "
        "pending and never restores a superseded verdict. latest_comment is the comment "
        "of the most recent event carrying one, whatever its type. latest_decision_id "
        "and decision_recorded_at describe the most recent event of any type, so "
        "appending a comment moves them.';"
    )


