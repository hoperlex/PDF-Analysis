def _create_project_and_documents() -> None:
    op.execute(
        f"""
        CREATE TABLE project (
            project_uid text PRIMARY KEY,
            name        text NOT NULL,
            created_at  timestamptz NOT NULL DEFAULT now(),
            updated_at  timestamptz NOT NULL DEFAULT now(),
            CONSTRAINT ck_project_project_uid_format CHECK ({id_check('project_uid', 'prj')}),
            CONSTRAINT ck_project_name_length CHECK (char_length(name) BETWEEN 1 AND 200)
        );
        """
    )
    op.execute(
        "COMMENT ON COLUMN project.name IS "
        "'Display label chosen by the expert. Not unique, not an identity and never a "
        "foreign key: two projects may legitimately carry the same name.';"
    )

    op.execute(
        f"""
        CREATE TABLE document (
            document_uid        text PRIMARY KEY,
            project_uid         text NOT NULL REFERENCES project (project_uid),
            display_title       text NOT NULL,
            current_version_uid text NULL,
            created_at          timestamptz NOT NULL DEFAULT now(),
            updated_at          timestamptz NOT NULL DEFAULT now(),
            CONSTRAINT ck_document_document_uid_format
                CHECK ({id_check('document_uid', 'doc')}),
            CONSTRAINT ck_document_project_uid_format
                CHECK ({id_check('project_uid', 'prj')}),
            CONSTRAINT ck_document_current_version_uid_format
                CHECK (current_version_uid IS NULL
                       OR {id_check('current_version_uid', 'ver')}),
            CONSTRAINT ck_document_display_title_length
                CHECK (char_length(display_title) BETWEEN 1 AND 400)
        );
        """
    )
    op.execute("CREATE INDEX ix_document_project_uid ON document (project_uid);")
    op.execute(
        "COMMENT ON COLUMN document.display_title IS "
        "'Presentation value. A human sheet or document number is not an identity and "
        "is never a foreign key.';"
    )

    op.execute(
        f"""
        CREATE TABLE document_version (
            version_uid      text PRIMARY KEY,
            document_uid     text NOT NULL REFERENCES document (document_uid),
            version_ordinal  integer NOT NULL,
            state            text NOT NULL DEFAULT 'published',
            source_filename  text NULL,
            media_type       text NOT NULL,
            byte_size        bigint NOT NULL,
            sha256           text NOT NULL,
            page_count       integer NOT NULL,
            published_at     timestamptz NOT NULL DEFAULT now(),
            created_at       timestamptz NOT NULL DEFAULT now(),
            CONSTRAINT ck_document_version_version_uid_format
                CHECK ({id_check('version_uid', 'ver')}),
            CONSTRAINT ck_document_version_document_uid_format
                CHECK ({id_check('document_uid', 'doc')}),
            CONSTRAINT ck_document_version_state CHECK (state = 'published'),
            CONSTRAINT ck_document_version_ordinal CHECK (version_ordinal >= 1),
            CONSTRAINT ck_document_version_byte_size CHECK (byte_size >= 0),
            CONSTRAINT ck_document_version_sha256 CHECK (sha256 {SHA256}),
            CONSTRAINT ck_document_version_page_count
                CHECK (page_count BETWEEN 1 AND 30),
            CONSTRAINT ck_document_version_media_type
                CHECK (media_type = 'application/pdf'),
            CONSTRAINT uq_document_version_document_uid_version_ordinal
                UNIQUE (document_uid, version_ordinal),
            CONSTRAINT uq_document_version_document_uid_version_uid
                UNIQUE (document_uid, version_uid)
        );
        """
    )
    op.execute(
        "COMMENT ON COLUMN document_version.version_ordinal IS "
        "'Display and ordering value only: v1, v2, v3 as a reviewer reads them. The "
        "contract lists a display ordinal among the non-identities, so nothing in this "
        "schema references it - grep for foreign keys and you will find none. It is "
        "unique per document so version-ordering misuse is detectable at ingest.';"
    )
    op.execute(
        "COMMENT ON COLUMN document_version.source_filename IS "
        "'The uploaded file name, retained for display. Explicitly not an identity: it "
        "is nullable, not unique and referenced by nothing.';"
    )
    op.execute(
        "COMMENT ON COLUMN document_version.page_count IS "
        "'Bounded by the PC-01 input envelope: at most 30 pages. An over-page-count "
        "file is refused by the admission probe with validation_failed before it "
        "reaches this table; the CHECK is the backstop, not the message.';"
    )
    op.execute(
        "COMMENT ON TABLE document_version IS "
        "'A published DocumentVersion is immutable. UPDATE and DELETE are refused by "
        "trigger; a corrected source file creates a new version_uid. PC-01 has no "
        "Import aggregate, so a version row exists only in the published state.';"
    )

    # Closes the cycle: a document points at one of *its own* versions. The composite
    # reference makes pointing at another document's version impossible rather than
    # merely wrong.
    op.execute(
        """
        ALTER TABLE document
            ADD CONSTRAINT fk_document_current_version_document_version
            FOREIGN KEY (document_uid, current_version_uid)
            REFERENCES document_version (document_uid, version_uid);
        """
    )


