# 2. The declared state topology, as data
# ---------------------------------------------------------------------------


def _create_contract_topology() -> None:
    op.execute(
        """
        CREATE TABLE contract_state_transition (
            machine    text NOT NULL,
            from_state text NULL,
            to_state   text NOT NULL,
            CONSTRAINT ck_contract_state_transition_machine
                CHECK (machine IN ('audit_run', 'blob', 'command_idempotency')),
            CONSTRAINT uq_contract_state_transition_edge
                UNIQUE NULLS NOT DISTINCT (machine, from_state, to_state)
        );
        """
    )
    op.execute(
        "COMMENT ON TABLE contract_state_transition IS "
        "'The declared state topology of contracts/domain/v1/state-machines.json for "
        "the three machines PC-01 instantiates. A NULL from_state declares the initial "
        "state - the only state an INSERT may create. Reference data, not a domain "
        "aggregate: no business row references it. A state with no outgoing row is "
        "terminal by construction.';"
    )
    rows = ", ".join(
        "('{machine}', {origin}, '{target}')".format(
            machine=machine,
            origin="NULL" if origin is None else f"'{origin}'",
            target=target,
        )
        for machine, origin, target in STATE_TOPOLOGY
    )
    op.execute(
        f"INSERT INTO contract_state_transition (machine, from_state, to_state) VALUES {rows};"
    )


