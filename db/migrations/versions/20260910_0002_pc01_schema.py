# 1. Guard functions
# ---------------------------------------------------------------------------


def _create_guard_functions() -> None:
    # Append-only ledger: no UPDATE, no DELETE, ever. The frozen catalog names this
    # case under state_transition_not_allowed - "delete a decision event".
    op.execute(
        """
        CREATE FUNCTION am_append_only() RETURNS trigger
        LANGUAGE plpgsql AS $fn$
        BEGIN
            RAISE EXCEPTION
                'state_transition_not_allowed: % is an append-only ledger; % is refused',
                TG_TABLE_NAME, TG_OP
                USING ERRCODE = 'AM002',
                      HINT = 'Append a new event. A recorded event is never rewritten '
                             'or removed, and the current value is a projection over '
                             'the stream.';
        END
        $fn$;
        """
    )

    # Immutable row: written once, never rewritten. Used for published input state
    # and for emitted evidence.
    op.execute(
        """
        CREATE FUNCTION am_immutable_row() RETURNS trigger
        LANGUAGE plpgsql AS $fn$
        BEGIN
            RAISE EXCEPTION
                'state_transition_not_allowed: % is immutable once written; % is refused',
                TG_TABLE_NAME, TG_OP
                USING ERRCODE = 'AM003',
                      HINT = 'Correcting data creates a new entity with a new '
                             'identifier; it never rewrites an existing one.';
        END
        $fn$;
        """
    )

    # The state guard. One function, parameterised by machine name and state column,
    # reading the declared topology out of contract_state_transition. There is no
    # permissive default: an edge that is not declared is refused.
    op.execute(
        """
        CREATE FUNCTION am_guard_state_transition() RETURNS trigger
        LANGUAGE plpgsql AS $fn$
        DECLARE
            v_machine text := TG_ARGV[0];
            v_column  text := TG_ARGV[1];
            v_old     text;
            v_new     text;
        BEGIN
            EXECUTE format('SELECT ($1).%I', v_column) INTO v_new USING NEW;

            IF TG_OP = 'INSERT' THEN
                IF NOT EXISTS (
                    SELECT 1 FROM contract_state_transition
                    WHERE machine = v_machine
                      AND from_state IS NULL
                      AND to_state = v_new
                ) THEN
                    RAISE EXCEPTION
                        'state_transition_not_allowed: % may not be created in state %',
                        v_machine, v_new
                        USING ERRCODE = 'AM001',
                              DETAIL = 'machine=' || v_machine
                                       || ', current_state=<none>, requested_state='
                                       || coalesce(v_new, '<null>'),
                              HINT = 'Only the declared initial state may be inserted.';
                END IF;
                RETURN NEW;
            END IF;

            EXECUTE format('SELECT ($1).%I', v_column) INTO v_old USING OLD;

            IF v_old IS NOT DISTINCT FROM v_new THEN
                RETURN NEW;
            END IF;

            IF NOT EXISTS (
                SELECT 1 FROM contract_state_transition
                WHERE machine = v_machine
                  AND from_state = v_old
                  AND to_state = v_new
            ) THEN
                RAISE EXCEPTION
                    'state_transition_not_allowed: % has no declared transition % -> %',
                    v_machine, v_old, v_new
                    USING ERRCODE = 'AM001',
                          DETAIL = 'machine=' || v_machine
                                   || ', current_state=' || coalesce(v_old, '<null>')
                                   || ', requested_state=' || coalesce(v_new, '<null>'),
                          HINT = 'A terminal aggregate is never reopened. The '
                                 'corrective action is a new aggregate with a new '
                                 'identifier.';
            END IF;

            RETURN NEW;
        END
        $fn$;
        """
    )

    # Frozen columns: an UPDATE may move the state and the derived bookkeeping, and
    # nothing else. A run's frozen input and configuration set is never edited.
    op.execute(
        """
        CREATE FUNCTION am_guard_frozen_columns() RETURNS trigger
        LANGUAGE plpgsql AS $fn$
        DECLARE
            v_column text;
            v_old    text;
            v_new    text;
        BEGIN
            FOREACH v_column IN ARRAY TG_ARGV LOOP
                EXECUTE format('SELECT ($1).%I::text', v_column) INTO v_old USING OLD;
                EXECUTE format('SELECT ($1).%I::text', v_column) INTO v_new USING NEW;
                IF v_old IS DISTINCT FROM v_new THEN
                    RAISE EXCEPTION
                        'state_transition_not_allowed: %.% is frozen at creation and '
                        'may not be changed', TG_TABLE_NAME, v_column
                        USING ERRCODE = 'AM003',
                              HINT = 'A different value is a different entity. '
                                     'Create a new one with a new identifier.';
                END IF;
            END LOOP;
            RETURN NEW;
        END
        $fn$;
        """
    )

    # Write-once columns: NULL may become a value exactly once; a value never changes
    # and never returns to NULL. Blob verification metadata works this way.
    op.execute(
        """
        CREATE FUNCTION am_guard_write_once_columns() RETURNS trigger
        LANGUAGE plpgsql AS $fn$
        DECLARE
            v_column text;
            v_old    text;
            v_new    text;
        BEGIN
            FOREACH v_column IN ARRAY TG_ARGV LOOP
                EXECUTE format('SELECT ($1).%I::text', v_column) INTO v_old USING OLD;
                EXECUTE format('SELECT ($1).%I::text', v_column) INTO v_new USING NEW;
                IF v_old IS NOT NULL AND v_old IS DISTINCT FROM v_new THEN
                    RAISE EXCEPTION
                        'state_transition_not_allowed: %.% is write-once and already '
                        'carries a value', TG_TABLE_NAME, v_column
                        USING ERRCODE = 'AM003',
                              HINT = 'Verified content metadata is immutable. '
                                     'Different bytes are a different blob_id.';
                END IF;
            END LOOP;
            RETURN NEW;
        END
        $fn$;
        """
    )


