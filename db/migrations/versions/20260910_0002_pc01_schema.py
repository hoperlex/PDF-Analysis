"""P02 head: the complete PC-01 schema, with its invariants as database constraints.

This is the only migration that creates a product table, and it creates all of them
at once. The plan gives every Gate B session one frozen head to build against, so a
schema need arriving later is a request to this seam - a test plus the constraint it
wants - and never a second head.

Why the DDL is written out rather than autogenerated: the invariants that carry this
schema are not column types. They are append-only ledgers, immutable published rows
and a declared state topology, all of which live in triggers and CHECK constraints
that autogenerate does not write and does not notice going missing.

What is encoded here, and where it comes from:

* ``contracts/domain/v1/identifiers.json`` - the identifier format, as a CHECK on
  every identity column. An identifier failing the contract pattern is rejected by
  the database as well as by the value type, so a raw-SQL writer cannot bypass it.
  Nothing in this schema uses a path, an object key, a file name, a checksum or a
  display ordinal as a key: those columns exist, are named for what they are and are
  referenced by no foreign key.
* ``contracts/domain/v1/state-machines.json`` - the declared topology of the three
  machines PC-01 instantiates (``audit_run``, ``blob``, ``command_idempotency``),
  seeded as data into ``contract_state_transition`` and enforced by one trigger. An
  undeclared edge raises SQLSTATE ``AM001``; there is no permissive default.
  ``import``, ``job`` and ``attempt`` are not instantiated: PC-01 has no Import, no
  Job and no Attempt, so no table, no state column and no conformance claim.
* ``contracts/analysis/v1/stage-registry.json`` - the nine canonical stage ids and
  the four StageResult statuses, and the rule that a ``succeeded`` result carries no
  error.
* ``contracts/domain/v1/error-codes.json`` - the closed twenty-code catalog, as the
  domain of every column that records a typed failure.
* ``OD-12`` - the decision author identity is one configured local reviewer label,
  persisted server-side with each event. That is the ``author_label`` column, and
  deciding it later would have been a schema change.

Deliberately absent: job, attempt, lease, export, import, comparison, norms and
knowledge-base tables. PC-01 instantiates none of those aggregates, and the CSV
export is computed on request rather than stored.

Revision ID: 0002_pc01_schema
Revises: 0001_baseline
Created: 2026-09-10
"""

