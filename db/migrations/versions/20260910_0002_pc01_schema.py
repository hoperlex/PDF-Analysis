def _attach_guards() -> None:
    for table in (
        "document_version",
        "input_manifest_entry",
        "finding_observation",
        "finding_evidence",
        "model_call",
    ):
        op.execute(
            f"""
            CREATE TRIGGER trg_{table}_immutable
                BEFORE UPDATE OR DELETE ON {table}
                FOR EACH ROW EXECUTE FUNCTION am_immutable_row();
            """
        )

    for table in ("expert_decision_event", "audit_event"):
        op.execute(
            f"""
            CREATE TRIGGER trg_{table}_append_only
                BEFORE UPDATE OR DELETE ON {table}
                FOR EACH ROW EXECUTE FUNCTION am_append_only();
            """
        )

    op.execute(
        """
        CREATE TRIGGER trg_audit_run_state_guard
            BEFORE INSERT OR UPDATE ON audit_run
            FOR EACH ROW EXECUTE FUNCTION am_guard_state_transition('audit_run', 'state');
        """
    )
    op.execute(
        """
        CREATE TRIGGER trg_audit_run_frozen_guard
            BEFORE UPDATE ON audit_run
            FOR EACH ROW EXECUTE FUNCTION am_guard_frozen_columns(
                'run_id', 'project_uid', 'version_uid', 'analysis_profile_id',
                'prompt_bundle_id', 'norms_snapshot_id', 'provider_mode',
                'frozen_input_digest', 'created_at');
        """
    )
    op.execute(
        """
        CREATE TRIGGER trg_blob_state_guard
            BEFORE INSERT OR UPDATE ON blob
            FOR EACH ROW EXECUTE FUNCTION am_guard_state_transition('blob', 'state');
        """
    )
    op.execute(
        """
        CREATE TRIGGER trg_blob_write_once_guard
            BEFORE UPDATE ON blob
            FOR EACH ROW EXECUTE FUNCTION am_guard_write_once_columns(
                'sha256', 'size_bytes', 'media_type');
        """
    )
    op.execute(
        """
        CREATE TRIGGER trg_command_record_state_guard
            BEFORE INSERT OR UPDATE ON command_record
            FOR EACH ROW EXECUTE FUNCTION am_guard_state_transition(
                'command_idempotency', 'state');
        """
    )
    op.execute(
        """
        CREATE TRIGGER trg_command_record_frozen_guard
            BEFORE UPDATE ON command_record
            FOR EACH ROW EXECUTE FUNCTION am_guard_frozen_columns(
                'command_id', 'command_type', 'idempotency_key', 'payload_fingerprint');
        """
    )
    # The topology itself is reference data seeded by this migration. Freezing it
    # closes the obvious bypass: inserting an edge and then taking it.
    op.execute(
        """
        CREATE TRIGGER trg_contract_state_transition_immutable
            BEFORE INSERT OR UPDATE OR DELETE ON contract_state_transition
            FOR EACH ROW EXECUTE FUNCTION am_immutable_row();
        """
    )


def downgrade() -> None:
    """Drop the PC-01 schema, leaving the migrated-but-empty P01 baseline.

    Forward-only in practice. ``db/migrations/README.md``: a down file is not a
    substitute for data recovery, and this one destroys every finding, decision and
    audit event in the database. It exists so a *pre-consumer* revert is one command
    on a disposable local database, which is exactly the rollback the task
    specifies - never something to run against a populated one.
    """
    op.execute("DROP VIEW IF EXISTS finding_current_verdict;")
    for table in (
        "audit_event",
        "expert_decision_event",
        "finding_evidence",
        "finding_observation",
        "finding",
        "model_call",
        "stage_result",
        "audit_run",
        "command_record",
        "input_manifest_entry",
        "blob",
    ):
        op.execute(f"DROP TABLE IF EXISTS {table} CASCADE;")
    op.execute("ALTER TABLE document DROP CONSTRAINT IF EXISTS fk_document_current_version_document_version;")
    op.execute("DROP TABLE IF EXISTS document_version CASCADE;")
    op.execute("DROP TABLE IF EXISTS document CASCADE;")
    op.execute("DROP TABLE IF EXISTS project CASCADE;")
    op.execute("DROP TABLE IF EXISTS contract_state_transition CASCADE;")
    for function in (
        "am_guard_write_once_columns",
        "am_guard_frozen_columns",
        "am_guard_state_transition",
        "am_immutable_row",
        "am_append_only",
    ):
        op.execute(f"DROP FUNCTION IF EXISTS {function}();")
