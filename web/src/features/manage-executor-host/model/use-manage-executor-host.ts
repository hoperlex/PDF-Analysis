'use client';

/**
 * The commands on a server (`HOSTS-WEB-01`, ADR-0028): the switch «Использовать», «Удалить», the slots of a provider, the
 * command that connects a server and the install over SSH with the confirmation of its host key.
 *
 * Each takes the idempotency key its caller minted for the intent and reuses it on an explicit repeat; `retry: false`, so
 * nothing here repeats a write on its own. Every command invalidates `execution.all()`: the list of servers, a server's details
 * and the cells of the layout with no server all answer from what a command changes. None of them changes a number the
 * dashboard reads.
 *
 * **The command that connects a server is shown once.** `issueExecutorHostEnrollment` answers with the secret and the copyable
 * line; the stand keeps only a hash, so the mutation keeps no copy (`gcTime: 0`) and the window holds the value in its own state
 * for one reading and drops it.
 */

import { useMutation, useQueryClient } from '@tanstack/react-query';

import type {
  ExecutorAgentInstall,
  ExecutorAgentInstallAccess,
  ExecutorAgentInstallId,
  ExecutorHost,
  ExecutorHostId,
  ExecutorHostSlots,
  IssuedExecutorEnrollment,
} from '@/shared/api';
import {
  archiveExecutorHost,
  confirmExecutorHostAgentInstallHostKey,
  createExecutorHostAgentInstall,
  issueExecutorHostEnrollment,
  queryKeys,
  setExecutorHostEnabled,
  setExecutorHostSlots,
} from '@/shared/api';

function useRefreshExecution() {
  const client = useQueryClient();
  return () => {
    void client.invalidateQueries({ queryKey: queryKeys.execution.all() });
  };
}

/** The switch «Использовать». Off, the server takes no new run; the runs it holds finish. */
export function useSetExecutorHostEnabled() {
  const refresh = useRefreshExecution();
  return useMutation<ExecutorHost, unknown, { hostId: ExecutorHostId; enabled: boolean; idempotencyKey: string }>({
    mutationFn: async ({ hostId, enabled, idempotencyKey }) =>
      (await setExecutorHostEnabled({ path: { host_id: hostId }, body: { enabled }, idempotencyKey })).data,
    retry: false,
    onSuccess: refresh,
  });
}

/** «Удалить»: one-way, the server is archived and its token revoked. */
export function useArchiveExecutorHost() {
  const refresh = useRefreshExecution();
  return useMutation<ExecutorHost, unknown, { hostId: ExecutorHostId; idempotencyKey: string }>({
    mutationFn: async ({ hostId, idempotencyKey }) =>
      (await archiveExecutorHost({ path: { host_id: hostId }, idempotencyKey })).data,
    retry: false,
    onSuccess: refresh,
  });
}

/** How many calls of a provider the server may run at once. */
export function useSetExecutorHostSlots() {
  const refresh = useRefreshExecution();
  return useMutation<ExecutorHost, unknown, { hostId: ExecutorHostId; slots: ExecutorHostSlots; idempotencyKey: string }>({
    mutationFn: async ({ hostId, slots, idempotencyKey }) =>
      (await setExecutorHostSlots({ path: { host_id: hostId }, body: { slots }, idempotencyKey })).data,
    retry: false,
    onSuccess: refresh,
  });
}

/** «Командой в терминале»: creates the server and issues the one-time grant. No model is asked. */
export function useIssueExecutorHostEnrollment() {
  const refresh = useRefreshExecution();
  return useMutation<IssuedExecutorEnrollment, unknown, { displayName: string; idempotencyKey: string }>({
    mutationFn: async ({ displayName, idempotencyKey }) =>
      (await issueExecutorHostEnrollment({ body: { display_name: displayName }, idempotencyKey })).data,
    retry: false,
    gcTime: 0,
    onSuccess: refresh,
  });
}

export interface HostInstallRequest {
  readonly displayName: string;
  readonly sshHost: string;
  readonly sshPort: number;
  readonly sshUser: string;
  readonly access: ExecutorAgentInstallAccess;
  readonly idempotencyKey: string;
}

/** «По SSH»: creates the server and an install session. The key is generated by the stand; no model is asked. */
export function useCreateExecutorHostAgentInstall() {
  const refresh = useRefreshExecution();
  return useMutation<ExecutorAgentInstall, unknown, HostInstallRequest>({
    mutationFn: async ({ displayName, sshHost, sshPort, sshUser, access, idempotencyKey }) =>
      (await createExecutorHostAgentInstall({
        body: { display_name: displayName, ssh_host: sshHost, ssh_port: sshPort, ssh_user: sshUser, access },
        idempotencyKey,
      })).data,
    retry: false,
    onSuccess: refresh,
  });
}

/** The administrator confirms the fingerprint the worker saw; the stand refuses any other. */
export function useConfirmExecutorHostAgentInstallHostKey() {
  const refresh = useRefreshExecution();
  return useMutation<
    ExecutorAgentInstall,
    unknown,
    { hostId: ExecutorHostId; installId: ExecutorAgentInstallId; hostKeyFingerprint: string; idempotencyKey: string }
  >({
    mutationFn: async ({ hostId, installId, hostKeyFingerprint, idempotencyKey }) =>
      (await confirmExecutorHostAgentInstallHostKey({
        path: { host_id: hostId, install_id: installId },
        body: { host_key_fingerprint: hostKeyFingerprint },
        idempotencyKey,
      })).data,
    retry: false,
    onSuccess: refresh,
  });
}
